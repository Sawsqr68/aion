//! Per-item judgement: the mechanical battery AND the review panel, folded
//! into one accept/reject decision with its feedback and its violations.
//!
//! THE ACCEPTANCE RULE, in full. An item reaches `done` only when ALL of these
//! hold:
//!
//! 1. **The battery is green.** `gate.pass` false makes the item ineligible
//!    regardless of any verdict. A reviewer agent's opinion cannot overrule a
//!    recorded non-zero exit code — that inversion (opinion over measurement)
//!    is the exact defect this stage was added to close.
//! 2. **Every configured lens reported.** A missing lens is a recorded
//!    VIOLATION and rejects: an item accepted because one lens's activity never
//!    produced a verdict would be accepted on strictly less evidence than the
//!    operator configured. An EMPTY verdict set therefore never accepts.
//! 3. **Every reported lens accepts, DERIVED from its findings.** Any blocking
//!    finding rejects. The reviewer's asserted `overall` is CHECKED against
//!    that derivation, never trusted: a disagreement is its own recorded
//!    violation and is treated as reject.
//!
//! Both the gate failures and the rejecting verdicts are written into the
//! item's `feedback`, which is what the next round's RESUMED dev session reads.

use std::collections::{BTreeMap, BTreeSet};

use aion_worker::ActivityFailure;

use crate::types::{GateOutcome, GateRun, GatedItem, ItemVerdict, Lens, Overall, Severity};

use super::support::clip;

/// One judged item: accepted or rejected, with the feedback its next dev turn
/// reads and every derive-and-check violation observed on the way.
pub(super) struct Judgement {
    /// The gated result being judged (its coordinates become the `DoneItem`).
    pub(super) result: GatedItem,
    /// Whether the item may move to `done`.
    pub(super) accepted: bool,
    /// The feedback attached to the item when it cycles: the gate failures
    /// AND the rejecting verdicts.
    pub(super) feedback: String,
    /// Recorded protocol/consistency violations (evidence, never silent).
    pub(super) violations: Vec<String>,
}

/// Judge every gated item of one round against the panel's verdicts.
///
/// # Errors
///
/// Terminal on input violations that must never pass silently: two verdicts
/// from the same lens for the same item, a verdict naming an item this round
/// did not gate, or a verdict naming a lens the run did not configure. All
/// three can only be a wiring fault — the panel is machine-generated by
/// `plan_reviews` and the worker STAMPS each verdict's item and lens from the
/// seat it dispatched.
pub(super) fn judge_round(
    gated: Vec<GatedItem>,
    verdicts: &[ItemVerdict],
    lenses: &[Lens],
) -> Result<Vec<Judgement>, ActivityFailure> {
    let gated_ids: BTreeSet<&str> = gated.iter().map(|entry| entry.item.id.as_str()).collect();
    let configured: BTreeSet<&str> = lenses.iter().map(|lens| lens.name.as_str()).collect();
    let mut by_seat: BTreeMap<(&str, &str), &ItemVerdict> = BTreeMap::new();
    for verdict in verdicts {
        let item_id = verdict.item_id.as_str();
        let lens = verdict.lens.as_str();
        if !gated_ids.contains(item_id) {
            return Err(ActivityFailure::terminal(format!(
                "verdict from lens {lens:?} names item {item_id}, which this round \
                 did not gate — the panel is generated from the round's gated items, \
                 so this is a wiring fault"
            )));
        }
        if !configured.contains(lens) {
            return Err(ActivityFailure::terminal(format!(
                "verdict for item {item_id} names lens {lens:?}, which the run did \
                 not configure — the worker stamps each verdict's lens from the \
                 dispatched panel seat, so this is a wiring fault"
            )));
        }
        if by_seat.insert((item_id, lens), verdict).is_some() {
            return Err(ActivityFailure::terminal(format!(
                "two verdicts for item {item_id} from lens {lens:?} — one panel seat \
                 produces exactly one verdict"
            )));
        }
    }

    Ok(gated
        .into_iter()
        .map(|result| judge_item(result, &by_seat, lenses))
        .collect())
}

/// Judge ONE gated item: the battery, then every configured lens.
fn judge_item(
    result: GatedItem,
    by_seat: &BTreeMap<(&str, &str), &ItemVerdict>,
    lenses: &[Lens],
) -> Judgement {
    let item_id = result.item.id.clone();
    let mut violations: Vec<String> = Vec::new();
    let mut rejections: Vec<String> = Vec::new();

    let gate_red = !result.gate.pass;
    if gate_red {
        violations.push(format!(
            "item {item_id}: the gate battery is RED — the item cannot be accepted \
             on any verdict"
        ));
    }

    let mut missing: Vec<&str> = Vec::new();
    for lens in lenses {
        let Some(verdict) = by_seat.get(&(item_id.as_str(), lens.name.as_str())) else {
            missing.push(lens.name.as_str());
            violations.push(format!(
                "item {item_id}: lens {:?} never reported — the item is judged on \
                 less evidence than the operator configured, so it is rejected",
                lens.name
            ));
            continue;
        };
        let checked = check_verdict(verdict);
        violations.extend(checked.violations);
        if checked.rejects {
            rejections.push(render_rejection(&lens.name, verdict));
        }
    }

    let accepted =
        !gate_red && missing.is_empty() && rejections.is_empty() && violations.is_empty();
    let feedback = if accepted {
        String::new()
    } else {
        render_feedback(&result.gate, &rejections, &missing)
    };
    Judgement {
        result,
        accepted,
        feedback,
        violations,
    }
}

/// The result of derive-and-check over ONE lens's verdict.
struct CheckedVerdict {
    rejects: bool,
    violations: Vec<String>,
}

/// DERIVE-AND-CHECK one verdict: the derived overall is reject iff any finding
/// is blocking. A verdict whose asserted overall disagrees, or a rejection
/// missing its `reject_reason` or a substantiating blocking finding, REJECTS
/// and the violation is recorded.
fn check_verdict(verdict: &ItemVerdict) -> CheckedVerdict {
    let has_blocking = verdict
        .findings
        .iter()
        .any(|finding| finding.severity == Severity::Blocking);
    let derived = if has_blocking {
        Overall::Reject
    } else {
        Overall::Accept
    };
    let mut violations = Vec::new();
    if verdict.overall != derived {
        violations.push(format!(
            "item {} lens {:?}: asserted overall {:?} disagrees with the derived \
             {derived:?} — treated as reject",
            verdict.item_id, verdict.lens, verdict.overall
        ));
    }
    let rejects = derived == Overall::Reject || verdict.overall == Overall::Reject;
    let reason_missing = rejects
        && verdict
            .reject_reason
            .as_deref()
            .is_none_or(|reason| reason.trim().is_empty());
    if reason_missing {
        violations.push(format!(
            "item {} lens {:?}: rejection carries no reject_reason",
            verdict.item_id, verdict.lens
        ));
    }
    if verdict.overall == Overall::Reject && !has_blocking {
        violations.push(format!(
            "item {} lens {:?}: rejection carries no substantiating blocking finding",
            verdict.item_id, verdict.lens
        ));
    }
    CheckedVerdict {
        rejects,
        violations,
    }
}

/// Render one lens's rejection as the line the next dev turn reads: the lens
/// name, the reason, and every blocking finding's title.
fn render_rejection(lens_name: &str, verdict: &ItemVerdict) -> String {
    let reason = verdict
        .reject_reason
        .as_deref()
        .filter(|reason| !reason.trim().is_empty())
        .unwrap_or("(no reject_reason given)");
    let blocking_titles: Vec<&str> = verdict
        .findings
        .iter()
        .filter(|finding| finding.severity == Severity::Blocking)
        .map(|finding| finding.title.as_str())
        .collect();
    if blocking_titles.is_empty() {
        format!("{lens_name}: {reason}")
    } else {
        format!(
            "{lens_name}: {reason} [blocking: {}]",
            blocking_titles.join("; ")
        )
    }
}

/// The item's `feedback` for its next (RESUMED) dev session: the mechanical
/// battery's failures FIRST — they are objective and usually the cause of the
/// review findings — then the panel's rejections, then any lens that did not
/// report at all. Clipped so a pathological battery tail cannot dwarf the
/// prompt it rides in.
fn render_feedback(gate: &GateOutcome, rejections: &[String], missing: &[&str]) -> String {
    let mut sections: Vec<String> = Vec::new();
    if !gate.pass {
        let red: Vec<String> = gate
            .runs
            .iter()
            .filter(|run| !run.passed)
            .map(render_red_run)
            .collect();
        let body = if red.is_empty() {
            // No individual command failed, so the battery failed on the
            // handler's own tree assertion: the diagnostics carry the reason.
            gate.diagnostics.clone()
        } else {
            format!("{}\n\n{}", red.join("\n\n"), gate.diagnostics)
        };
        sections.push(format!(
            "THE GATE BATTERY IS RED — fix this first; no verdict can accept the \
             item while it is red:\n\n{body}"
        ));
    }
    if !rejections.is_empty() {
        sections.push(format!(
            "THE REVIEW PANEL REJECTED THIS ROUND:\n\n{}",
            rejections
                .iter()
                .map(|line| format!("- {line}"))
                .collect::<Vec<_>>()
                .join("\n")
        ));
    }
    if !missing.is_empty() {
        sections.push(format!(
            "NO VERDICT ARRIVED from the configured lens(es) [{}] — the round is \
             rejected because the item was judged on less evidence than \
             configured, not because of anything you did.",
            missing.join(", ")
        ));
    }
    if sections.is_empty() {
        // Reached only when a derive-and-check violation rejected the round
        // without producing a rejection line; never leave the dev agent
        // guessing why its round cycled.
        sections.push(
            "The round was rejected on a verdict-consistency violation recorded in \
             the run's evidence; the panel produced no usable rejection reason."
                .to_owned(),
        );
    }
    clip(&sections.join("\n\n"))
}

/// One red gate command rendered for the dev agent: the real (resolved) argv,
/// the exit code, and the output tail.
fn render_red_run(run: &GateRun) -> String {
    format!(
        "gate `{}` exited {} running `{}`:\n{}",
        run.name,
        run.exit_code,
        run.argv.join(" "),
        run.output_tail.trim()
    )
}
