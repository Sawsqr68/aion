/**
 * The gate that catches protobuf rot.
 *
 * This SDK's committed stubs drifted from the wire contract and every test in
 * this suite kept passing. Not because the tests forgot to check something —
 * because the tests' REFERENCE drifted in lockstep with the thing under test.
 * The stubs and the suite shared one fossil, so a green was never two facts
 * agreeing; it was one fact told twice. `RegisterWorker` lost `namespace` and
 * gained `namespaces` / `task_queue` / `node` / `activities` / `identity`; the
 * SDK could not register with a live server; nothing anywhere went red.
 *
 * A documented regeneration ritual does not help, because nobody performs a
 * ritual to discover a problem they do not know they have. So the comparison
 * runs here, in the ordinary test run.
 */

import { existsSync, readFileSync, readdirSync, rmSync } from "node:fs";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import {
	compareWithCommitted,
	generateIntoTempDir,
	generatedFileNames,
	OUTPUT_DIR,
	PROTO_DIR,
	PROTO_FILES,
} from "../scripts/generate-proto.mjs";

const scratchDirs: string[] = [];

function freshGeneration(): string {
	const directory = generateIntoTempDir();
	scratchDirs.push(directory);
	return directory;
}

afterAll(() => {
	for (const directory of scratchDirs) {
		rmSync(directory, { recursive: true, force: true });
	}
});

describe("protobuf contract location", () => {
	it("the authoritative proto directory actually exists", () => {
		// The original rot: the generator pointed at `crates/aion-proto/proto`,
		// which had been deleted. `npm run build` failed for everyone and no
		// test said so.
		expect(
			existsSync(PROTO_DIR),
			`${PROTO_DIR} is not a directory; the shared wire contract has moved and ` +
				"PROTO_DIR in scripts/generate-proto.mjs is stale",
		).toBe(true);
	});

	it.each(PROTO_FILES)("compiles %s, which must be present", (name) => {
		expect(
			existsSync(join(PROTO_DIR, name)),
			`generate-proto.mjs compiles ${name}, but it is not in ${PROTO_DIR}`,
		).toBe(true);
	});
});

describe("committed protobuf artifacts", () => {
	it("byte-matches what the current wire contract generates today", () => {
		// The gate that actually catches the rot. Byte comparison is the right
		// strictness: a "do the fields we use still exist" check would let a
		// field the SDK does not yet send appear and go unnoticed — which is
		// the exact failure, since `activities` was added and ignored.
		//
		// If this fails, the fix is to regenerate and commit, then make the SDK
		// speak whatever changed. It is never to relax the comparison.
		const fresh = freshGeneration();
		const { missing, unexpected, differing } = compareWithCommitted(fresh);

		expect(
			differing,
			`the committed protobuf stubs are STALE: ${differing.join(", ")} differ from ` +
				`what ${PROTO_DIR} generates today. The SDK is speaking an older wire ` +
				"contract than the server. Run `npm run generate:proto`, commit the " +
				"result, then update the SDK for whatever changed.",
		).toEqual([]);
		expect(
			missing,
			`protoc emits ${missing.join(", ")} but they are not committed in ` +
				`${OUTPUT_DIR}. Run \`npm run generate:proto\` and commit the result.`,
		).toEqual([]);
		expect(
			unexpected,
			`${unexpected.join(", ")} sit in ${OUTPUT_DIR} but no regeneration produces ` +
				"them. A hand-written file among generated neighbours is invisible to " +
				"this gate forever — move it out of src/proto/ rather than widening " +
				"the exclusion set.",
		).toEqual([]);
	});

	it("contains ONLY generated files, so nothing escapes the gate", () => {
		// Pins the absence of hand-maintained strays. `src/proto/index.ts` used
		// to be one: a hand-written barrel sitting among generated neighbours
		// that regeneration would silently destroy and no comparison covered.
		const fresh = freshGeneration();

		expect(generatedFileNames(OUTPUT_DIR)).toEqual(generatedFileNames(fresh));
		expect(
			readdirSync(OUTPUT_DIR).filter((name) => !name.endsWith(".ts")),
			`${OUTPUT_DIR} must contain only generated .ts files`,
		).toEqual([]);
	});

	it("carries the generated banner, so no one edits them by hand", () => {
		for (const name of generatedFileNames(OUTPUT_DIR)) {
			expect(
				readFileSync(join(OUTPUT_DIR, name), "utf8").startsWith(
					"// Code generated by protoc-gen-ts_proto. DO NOT EDIT.",
				),
				`${name} lost its generated banner`,
			).toBe(true);
		}
	});
});

describe("protobuf generator", () => {
	it("is reproducible: two runs agree byte for byte", () => {
		// A gate that fails intermittently gets disabled, and a disabled gate is
		// how the stubs went stale in the first place. The drift gate above must
		// not be able to become the thing it replaced. If protoc or ts-proto
		// ever starts emitting a timestamp or a nondeterministic ordering, this
		// fails FIRST and names the reason, instead of the drift test failing
		// mysteriously on an unrelated change.
		//
		// Verified deterministic for protoc 3.19.1 / protoc-gen-ts_proto 2.11.8.
		// Note the generated banner pins both tool versions, so a toolchain bump
		// legitimately changes the bytes: regenerate and commit, do not
		// normalize the comparison.
		const first = freshGeneration();
		const second = freshGeneration();

		const firstNames = generatedFileNames(first);
		expect(generatedFileNames(second)).toEqual(firstNames);
		for (const name of firstNames) {
			expect(
				readFileSync(join(first, name)).equals(readFileSync(join(second, name))),
				`the generator is NONDETERMINISTIC for ${name}: two runs of the same ` +
					"inputs produced different bytes. Do not normalize this away — the " +
					"drift gate cannot be trusted until the generator is reproducible.",
			).toBe(true);
		}
	});
});
